import assert from "node:assert/strict";
import { readFile, readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

async function htmlFiles(root, directory = "") {
  const files = [];
  for (const entry of await readdir(path.join(root, directory), {
    withFileTypes: true,
  })) {
    const relative = path.posix.join(directory, entry.name);
    if (entry.isDirectory() && entry.name !== "_next") {
      files.push(...(await htmlFiles(root, relative)));
    } else if (entry.isFile() && entry.name.endsWith(".html")) {
      files.push(relative);
    }
  }
  return files.sort();
}

async function inspectExport(directory) {
  const root =
    directory instanceof URL
      ? fileURLToPath(directory)
      : path.resolve(directory);
  const files = await htmlFiles(root);
  assert(
    files.includes("index.html") && files.includes("404.html"),
    "Missing exported home or 404 page"
  );
  const pages = [];
  for (const file of files) {
    const html = await readFile(path.join(root, file), "utf8");
    const data = html.match(
      /<script\b[^>]*\bid="__NEXT_DATA__"[^>]*>(.*?)<\/script>/s
    );
    assert(data, `Missing Next page data in ${file}`);
    const page = JSON.parse(data[1]);
    assert(
      !page.assetPrefix,
      `Unexpected asset prefix in ${file}: ${page.assetPrefix}`
    );
    assert(
      !html.includes('"/tzsafe-ui/'),
      `GitHub Pages basePath found in ${file}`
    );
    assert(page.nextExport || page.gsp, `${file} is not a static Next export`);
    for (const [, asset] of html.matchAll(
      /\b(?:src|href)="(\/_next\/[^"?#]+)[^\"]*"/g
    )) {
      assert(
        (await stat(path.join(root, decodeURIComponent(asset)))).isFile(),
        `Missing asset ${asset} in ${file}`
      );
    }
    if (page.page !== "/" && page.page !== "/404") {
      assert(
        !page.page.includes("..."),
        "Catch-all routes need an explicit IPFS mapping"
      );
      pages.push({ route: page.page, file, dynamic: page.page.includes("[") });
    }
  }
  // Static pages must win over the single-segment /:walletAddress route.
  pages.sort(
    (a, b) =>
      Number(a.dynamic) - Number(b.dynamic) ||
      b.route.split("/").length - a.route.split("/").length ||
      a.route.localeCompare(b.route)
  );
  const lines = [
    "# Generated by npm run build:ipfs. Requires a subdomain or DNSLink IPFS gateway.",
    "# 200 rewrites hydrate the exported Next page without a server-side 404 fallback.",
  ];
  for (const { route, file } of pages) {
    const from = route.replace(/\[([^\]]+)\]/g, ":$1");
    lines.push(`${from} /${file} 200`, `${from}/ /${file} 200`);
  }
  lines.push("/* /404.html 404", "");
  return { root, files, redirects: lines.join("\n") };
}

export async function validateIpfsExport(directory) {
  const inspected = await inspectExport(directory);
  const redirects = await readFile(
    path.join(inspected.root, "_redirects"),
    "utf8"
  );
  assert.equal(
    redirects,
    inspected.redirects,
    "Missing or stale IPFS routing rules; run npm run build:ipfs"
  );
  console.log(
    `IPFS export verified: ${inspected.files.length} HTML pages, root-relative assets, static and wallet routes.`
  );
  return inspected;
}

export async function prepareIpfsExport(directory) {
  const inspected = await inspectExport(directory);
  await writeFile(path.join(inspected.root, "_redirects"), inspected.redirects);
  await validateIpfsExport(directory);
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await validateIpfsExport(process.argv[2] ?? "out-ipfs");
}
